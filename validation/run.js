#!/usr/bin/env node
// Validation harness: run the engine against published figures and report the agreement.
//
// This is not the test suite. The tests check that the engine behaves the way the physics says;
// these cases check that the numbers it produces match numbers someone else published, and they
// report the error whether or not it is inside tolerance. A case that drifts is interesting even
// when it still passes, so every comparison is printed.
//
//   node validation/run.js                 report to stdout
//   node validation/run.js --markdown      also rewrite validation/REPORT.md
//   node validation/run.js --case pv-stc   run one case
//
// Exit status is non-zero if any comparison is outside its stated tolerance.

import { readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { dirname, join } from "node:path";
import { catalog } from "./harness.js";

const here = dirname(fileURLToPath(import.meta.url));

const args = process.argv.slice(2);
const wantMarkdown = args.includes("--markdown");
const only = args.includes("--case") ? args[args.indexOf("--case") + 1] : null;

async function loadCases() {
  const files = readdirSync(join(here, "cases"))
    .filter((name) => name.endsWith(".js"))
    .sort();
  const cases = [];
  for (const file of files) {
    const module = await import(pathToFileURL(join(here, "cases", file)).href);
    const validation = module.default;
    if (!validation?.id) throw new Error(`${file} does not export a validation case`);
    cases.push({ ...validation, file });
  }
  return cases;
}

/** Relative error, or absolute error when the published figure is zero. */
function errorOf(published, measured) {
  if (published === 0) return { value: Math.abs(measured), relative: false };
  return { value: Math.abs(measured - published) / Math.abs(published), relative: true };
}

function formatRow(row) {
  const error = errorOf(row.published, row.measured);
  const pass = error.value <= row.tolerance;
  const shown = error.relative
    ? `${(error.value * 100).toFixed(2)} %`
    : error.value.toExponential(2);
  const allowed = error.relative ? `${(row.tolerance * 100).toFixed(1)} %` : `${row.tolerance}`;
  return {
    pass,
    cells: [
      row.quantity,
      `${format(row.published)} ${row.unit}`,
      `${format(row.measured)} ${row.unit}`,
      shown,
      allowed,
      pass ? "ok" : "OUT"
    ]
  };
}

function format(value) {
  if (!Number.isFinite(value)) return String(value);
  const magnitude = Math.abs(value);
  if (magnitude !== 0 && (magnitude < 1e-3 || magnitude >= 1e6)) return value.toExponential(3);
  const digits = magnitude >= 100 ? 1 : magnitude >= 1 ? 2 : 4;
  return value.toFixed(digits);
}

function table(rows) {
  const widths = rows[0].map((_, column) =>
    Math.max(...rows.map((row) => String(row[column]).length))
  );
  return rows.map((row) =>
    row.map((cell, column) => String(cell).padEnd(widths[column])).join("  ").trimEnd()
  );
}

const cases = await loadCases();
const selected = only ? cases.filter((entry) => entry.id === only) : cases;
if (selected.length === 0) {
  console.error(only ? `No case with id "${only}"` : "No cases found");
  process.exit(2);
}

const report = [];
let failures = 0;
let comparisons = 0;

for (const validation of selected) {
  const references = [validation.reference].flat();
  for (const key of references) {
    if (!catalog.references[key]) {
      throw new Error(`Case ${validation.id} cites unknown reference "${key}"`);
    }
  }
  const started = Date.now();
  const rows = validation.run();
  const elapsed = (Date.now() - started) / 1000;

  const formatted = rows.map(formatRow);
  const failed = formatted.filter((row) => !row.pass).length;
  failures += failed;
  comparisons += rows.length;

  const body = table([
    ["quantity", "published", "model", "error", "allowed", ""],
    ...formatted.map((row) => row.cells)
  ]);

  report.push({
    validation,
    references: references.map((key) => ({ key, title: catalog.references[key].title })),
    body,
    failed,
    elapsed,
    rows
  });

  console.log(`\n${validation.id}: ${validation.title}`);
  for (const { key, title } of report[report.length - 1].references) {
    console.log(`  source  ${key} — ${title}`);
  }
  console.log(`  claim   ${validation.claim}`);
  for (const line of body) console.log(`  ${line}`);
  console.log(
    `  ${failed === 0 ? "all comparisons inside tolerance" : `${failed} outside tolerance`}` +
      ` (${rows.length} comparisons, ${elapsed.toFixed(1)} s)`
  );
}

console.log(
  `\n${selected.length} cases, ${comparisons} comparisons, ${failures} outside tolerance`
);

if (wantMarkdown) {
  const lines = [
    "# Validation report",
    "",
    "Generated by `npm run validate`. Every figure in the `published` column comes from the",
    "reference named beside it; every figure in the `model` column is what the engine produced",
    "in this run. Nothing here is fitted: the published number is not an input to the model.",
    "",
    `${selected.length} cases, ${comparisons} comparisons, ${failures} outside tolerance.`,
    ""
  ];
  for (const entry of report) {
    lines.push(`## ${entry.validation.id}: ${entry.validation.title}`, "");
    for (const { key, title } of entry.references) {
      lines.push(`- Source \`${key}\`: ${title}`);
    }
    lines.push("", entry.validation.claim, "");
    lines.push("| quantity | published | model | error | allowed | |");
    lines.push("| --- | --- | --- | --- | --- | --- |");
    for (const row of entry.rows) {
      const { cells } = formatRow(row);
      lines.push(`| ${cells.join(" | ")} |`);
    }
    lines.push("");
  }
  writeFileSync(join(here, "REPORT.md"), `${lines.join("\n")}\n`);
  console.log("wrote validation/REPORT.md");
}

process.exit(failures === 0 ? 0 : 1);
